-- Skema Database PostgreSQL untuk Sistem Catatan Gangguan TI (INA Digital)

CREATE TABLE IF NOT EXISTS users (
    id SERIAL PRIMARY KEY,
    username VARCHAR(50) UNIQUE NOT NULL,
    email VARCHAR(120) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    nama_lengkap VARCHAR(120) NOT NULL,
    unit_kerja VARCHAR(120) NOT NULL DEFAULT 'Pusat Data & Operasional TI',
    peran VARCHAR(50) NOT NULL DEFAULT 'Teknisi TI',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS gangguan_ti (
    id SERIAL PRIMARY KEY,
    kode_gangguan VARCHAR(40) UNIQUE NOT NULL,
    judul VARCHAR(200) NOT NULL,
    deskripsi TEXT NOT NULL,
    kategori VARCHAR(60) NOT NULL CHECK (
        kategori IN (
            'Jaringan',
            'Server & Infrastruktur',
            'Aplikasi',
            'Database',
            'Keamanan Siber',
            'Perangkat Keras'
        )
    ),
    status VARCHAR(40) NOT NULL CHECK (
        status IN (
            'Terbuka',
            'Dalam Penanganan',
            'Menunggu Pihak Ketiga',
            'Selesai',
            'Ditutup'
        )
    ),
    prioritas VARCHAR(30) NOT NULL DEFAULT 'Sedang' CHECK (
        prioritas IN ('Rendah', 'Sedang', 'Tinggi', 'Kritis')
    ),
    tanggal_kejadian DATE NOT NULL,
    durasi_downtime INTEGER NOT NULL DEFAULT 0 CHECK (durasi_downtime >= 0),
    jumlah_pengguna_terdampak INTEGER NOT NULL DEFAULT 0 CHECK (jumlah_pengguna_terdampak >= 0),
    biaya_pemulihan NUMERIC(15, 2) NOT NULL DEFAULT 0 CHECK (biaya_pemulihan >= 0),
    sistem_terdampak VARCHAR(150) NOT NULL,
    pelapor VARCHAR(120) NOT NULL,
    penanggung_jawab VARCHAR(120) NOT NULL DEFAULT 'Tim Tanggap Insiden TI',
    akar_masalah TEXT DEFAULT '',
    tindakan_perbaikan TEXT DEFAULT '',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

